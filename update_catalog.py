#!/usr/bin/env python3
"""Rebuild js/data.js from catalog/books.csv and the cover images in catalog/covers/.

Usage:  python3 update_catalog.py          (then refresh the website)
        python3 update_catalog.py --check  (validate only, write nothing)

See catalog/HOW_TO_ADD_BOOKS.md for the full guide.
"""
import csv
import json
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent
CSV_PATH = ROOT / "catalog" / "books.csv"
COVER_DIR = ROOT / "catalog" / "covers"
DATA_JS = ROOT / "js" / "data.js"
FRONT_DIR = ROOT / "assets" / "covers" / "front"
SPREAD_DIR = ROOT / "assets" / "covers" / "spread"

HEADER = """/**
 * Carmel Publications - Catalog Data Store
 * GENERATED by update_catalog.py from catalog/books.csv - edit the CSV, not the books list below.
 */
"""
GRADES = ["Nursery", "LKG", "UKG"] + [f"Grade {i}" for i in range(1, 13)]
ACCENTS = ["#3155E7", "#7928CA", "#0369A1", "#B91C1C", "#C2410C", "#047857", "#BE185D", "#4D7C0F"]
REQUIRED = ["title", "category", "grade", "price"]
IMG_EXT = (".png", ".jpg", ".jpeg", ".webp")


def slugify(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def hex_to_rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def load_existing():
    raw = DATA_JS.read_text(encoding="utf-8")
    start = raw.index("{")
    end = raw.rindex("}")
    return json.loads(raw[start:end + 1])


def find_image(name):
    if not name:
        return None
    path = COVER_DIR / name
    if path.is_file():
        return path
    for ext in IMG_EXT:  # allow the name without an extension
        if (COVER_DIR / (name + ext)).is_file():
            return COVER_DIR / (name + ext)
    return None


def save_cover(src, out_base, max_w, max_h, force):
    jpg, webp = out_base.with_suffix(".jpg"), out_base.with_suffix(".webp")
    if not force and jpg.exists() and webp.exists() and min(jpg.stat().st_mtime, webp.stat().st_mtime) >= src.stat().st_mtime:
        return
    out_base.parent.mkdir(parents=True, exist_ok=True)
    img = Image.open(src).convert("RGB")
    img.thumbnail((max_w, max_h), Image.LANCZOS)
    img.save(jpg, quality=88, optimize=True, progressive=True)
    img.save(webp, quality=82, method=6)


def expand_grades(level):
    """Return the list of grade tokens a level string covers; unknown tokens are returned as-is."""
    tokens = []
    for part in (p.strip() for p in level.split("/")):
        m = re.fullmatch(r"Grade\s*(\d+)\s*(?:-|\u2013|to)\s*(?:Grade\s*)?(\d+)", part, re.I)
        if m:
            tokens += [f"Grade {i}" for i in range(int(m[1]), int(m[2]) + 1)]
        else:
            tokens.append(part)
    return tokens


def to_bool(v):
    return str(v).strip().lower() in ("yes", "y", "true", "1", "x")


def main():
    check_only = "--check" in sys.argv
    errors, warnings = [], []
    data = load_existing()
    categories = {c["id"]: c for c in data["categories"]}
    cat_by_name = {c["name"].lower(): c for c in data["categories"]}
    collections = {c["id"]: c for c in data["collections"]}
    coll_by_name = {c["name"].lower(): c for c in data["collections"]}
    old_books = {b["id"]: b for b in data["books"]}

    with CSV_PATH.open(encoding="utf-8-sig", newline="") as fh:
        rows = [r for r in csv.DictReader(fh) if any((v or "").strip() for v in r.values())]

    books, seen = [], set()
    for n, row in enumerate(rows, start=2):  # row 1 is the header
        row = {k.strip().lower(): (v or "").strip() for k, v in row.items() if k}
        where = f"Row {n} ({row.get('title') or 'no title'})"
        missing = [c for c in REQUIRED if not row.get(c)]
        if missing:
            errors.append(f"{where}: missing {', '.join(missing)}")
            continue

        book_id = row.get("id") or slugify(row["title"])
        if book_id in seen:
            errors.append(f"{where}: duplicate id '{book_id}' (give the book a unique 'id')")
            continue
        seen.add(book_id)

        cat = cat_by_name.get(row["category"].lower()) or categories.get(slugify(row["category"]))
        if not cat:
            slug = slugify(row["category"])
            accent = ACCENTS[len(categories) % len(ACCENTS)]
            r, g, b = hex_to_rgb(accent)
            cat = {
                "id": slug, "name": row["category"], "tagline": "New series",
                "description": f"{row['category']} books from Carmel Publications.",
                "icon": "book-open", "count": 0, "accent": accent,
                "bg_gradient": f"linear-gradient(135deg, rgba({r}, {g}, {b}, 0.08), rgba({r}, {g}, {b}, 0.02))",
                "featured_book": book_id,
            }
            categories[slug] = cat
            cat_by_name[cat["name"].lower()] = cat
            warnings.append(f"New category created: '{row['category']}' (edit its text in js/data.js if you like)")

        coll_name = row.get("collection") or cat["name"]
        coll = coll_by_name.get(coll_name.lower()) or collections.get(slugify(coll_name))
        if not coll:
            coll = {"id": slugify(coll_name), "name": coll_name, "tagline": "Carmel Publications",
                    "description": f"{coll_name} from Carmel Publications.", "badge": "New"}
            collections[coll["id"]] = coll
            coll_by_name[coll_name.lower()] = coll
            warnings.append(f"New collection created: '{coll_name}'")

        tokens = expand_grades(row["grade"])
        for t in tokens:
            if t != "Pre-Primary" and t not in GRADES:
                errors.append(f"{where}: unknown grade '{t}'. Use Nursery, LKG, UKG, Grade 1 ... Grade 12, "
                              f"or ranges like 'Grade 6-8' and 'Grade 5 / Grade 6'")

        price_digits = re.sub(r"[^\d]", "", row["price"])
        if not price_digits:
            errors.append(f"{where}: price must be a number, e.g. 190")
            continue

        # Covers: new image in catalog/covers wins; otherwise keep the one already published.
        front_src = find_image(row.get("front_cover"))
        spread_src = find_image(row.get("full_cover"))
        if row.get("front_cover") and not front_src:
            errors.append(f"{where}: cover '{row['front_cover']}' not found in catalog/covers/")
        front_base = FRONT_DIR / book_id
        spread_base = SPREAD_DIR / book_id
        if front_src is None and not (front_base.with_suffix(".jpg").exists() and front_base.with_suffix(".webp").exists()):
            errors.append(f"{where}: no front cover. Put an image in catalog/covers/ and fill 'front_cover'")
        if row.get("full_cover") and not spread_src:
            errors.append(f"{where}: full cover '{row['full_cover']}' not found in catalog/covers/")

        orientation = (row.get("orientation") or "portrait").lower()
        if orientation not in ("portrait", "landscape"):
            errors.append(f"{where}: orientation must be 'portrait' or 'landscape'")
            orientation = "portrait"

        if not check_only and not errors:
            if front_src:
                save_cover(front_src, front_base, 540 if orientation == "landscape" else 480, 632, force=False)
            if spread_src:
                save_cover(spread_src, spread_base, 1200, 800, force=False)

        has_spread = spread_base.with_suffix(".jpg").exists() or spread_src is not None
        use = spread_base if has_spread else front_base
        old = old_books.get(book_id, {})
        try:
            rating = float(row["rating"]) if row.get("rating") else old.get("rating", 4.8)
        except ValueError:
            rating = 4.8
            warnings.append(f"{where}: rating is not a number, using 4.8")
        rel = lambda p: p.relative_to(ROOT).as_posix()  # noqa: E731

        books.append({
            "id": book_id,
            "title": row["title"],
            "subtitle": row.get("subtitle", ""),
            "category": cat["name"],
            "category_slug": cat["id"],
            "level": row["grade"],
            "age_group": row.get("age_group", ""),
            "collection": coll["name"],
            "collection_slug": coll["id"],
            "isbn": row.get("isbn", ""),
            "year": row.get("year", ""),
            "format": row.get("format", ""),
            "pages": int(row["pages"]) if row.get("pages", "").isdigit() else 0,
            "price": "\u20B9" + price_digits,
            "featured": to_bool(row.get("featured", "")),
            "rating": rating,
            "description": row.get("description", ""),
            "highlights": [h.strip() for h in row.get("highlights", "").split("|") if h.strip()],
            "cover_front_jpg": rel(front_base.with_suffix(".jpg")),
            "cover_front_webp": rel(front_base.with_suffix(".webp")),
            "cover_spread_jpg": rel(use.with_suffix(".jpg")),
            "cover_spread_webp": rel(use.with_suffix(".webp")),
            "aspect_type": orientation,
        })

    for w in dict.fromkeys(warnings):
        print("  note:", w)
    if errors:
        print("\nNothing was changed. Please fix these problems in catalog/books.csv:\n")
        for e in errors:
            print("  -", e)
        sys.exit(1)

    # Category counts / featured book are derived so they never go stale.
    used = []
    for cid, cat in categories.items():
        in_cat = [b for b in books if b["category_slug"] == cid]
        cat["count"] = len(in_cat)
        if in_cat and cat.get("featured_book") not in {b["id"] for b in in_cat}:
            cat["featured_book"] = next((b["id"] for b in in_cat if b["featured"]), in_cat[0]["id"])
        if in_cat:
            used.append(cat)

    data["books"] = books
    data["categories"] = used
    data["collections"] = [c for c in collections.values() if any(b["collection_slug"] == c["id"] for b in books)]
    data["publisher"].setdefault("stats", {}).update({
        "books_count": len(books), "categories_count": len(used), "collections_count": len(data["collections"]),
    })

    if check_only:
        print(f"OK - {len(books)} books, {len(used)} categories, {len(data['collections'])} collections (nothing written).")
        return
    DATA_JS.write_text(HEADER + "window.CATALOG_DATA = " + json.dumps(data, indent=2, ensure_ascii=False) + ";\n",
                       encoding="utf-8")
    print(f"Done - {len(books)} books, {len(used)} categories, {len(data['collections'])} collections written to js/data.js")


if __name__ == "__main__":
    main()
